def section(title, text, subtitle=None, items=(), fields=()):
    """Раздел документа в HTML: заголовок, текст, подзаголовок, список и выделенный блок."""

    parts = [f"<h2>{escape(title)}</h2>", f"<p>{escape(text)}</p>"]

    if subtitle:
        parts.append(f"<h3>{escape(subtitle)}</h3>")

    if items:
        parts.append("<ul>" + "".join(f"<li><p>{escape(item)}</p></li>" for item in items) + "</ul>")

    if fields:
        parts.append(
            "<blockquote>" + "".join(f"<p>{escape(field)}</p>" for field in fields) + "</blockquote>"
        )

    return "".join(parts)


